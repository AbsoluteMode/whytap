#!/usr/bin/env python3
"""Embed the Lil Bro sprite atlas (Resources/LilBro) into Swift source.

The atlas is a few kilobytes, so it ships inside the binary rather than as a
bundle resource: no packaging step can drop it, and offscreen tests read the
same bytes the app draws. Run after replacing any file in Resources/LilBro:

    python3 scripts/lilbro-embed-atlas.py

`LilBroAtlasTests` fails when the embedded copy and Resources/LilBro differ.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Resources" / "LilBro"
OUT = ROOT / "Sources" / "Sidekey" / "Settings" / "LilBro" / "LilBroAtlasData.swift"


def b64(name: str) -> str:
    return base64.b64encode((SRC / name).read_bytes()).decode("ascii")


def main() -> None:
    swift = f'''// Generated by scripts/lilbro-embed-atlas.py from Resources/LilBro. Do not edit.
// swiftlint:disable line_length

enum LilBroAtlasData {{
    static let json = "{b64("lilbro-hood.json")}"
    static let lightPNG = "{b64("lilbro-hood-light.png")}"
    static let darkPNG = "{b64("lilbro-hood-dark.png")}"
}}
'''
    OUT.write_text(swift)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
